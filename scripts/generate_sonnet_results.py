def main():
    # Load mini test cases
    data_dir = PROJECT_ROOT / "data" / "mini"
    loader = DataLoader(data_dir)
    cases = loader.load_all()
    print(f"Loaded {len(cases)} test cases from {data_dir}")

    # Create pre-generated adapter
    adapter = PreGeneratedAdapter(SONNET_RESPONSES, model_name="claude-sonnet-4")

    # Run benchmark
    config = BenchmarkConfig(
        subset="mini",
        run_llm_judge=False,  # No LLM judge for deterministic-only run
    )
    runner = BenchmarkRunner(model=adapter, data_dir=data_dir, cases=cases, config=config)
    results = runner.run()

    # Print summary
    print(results.summary())

    # Save results
    output_path = PROJECT_ROOT / "data" / "benchmark_results_sonnet.json"
    results.save(output_path)
    print(f"\nResults saved to: {output_path}")

    # Also save as formatted JSON
    with open(output_path, "r") as f:
        data = json.load(f)
    with open(output_path, "w") as f:
        json.dump(data, f, indent=2)
    print("Done.")


if __name__ == "__main__":
    main()
