class PreGeneratedAdapter:
    """Model adapter that returns pre-generated responses."""

    def __init__(self, responses: dict[str, str], model_name: str = "claude-sonnet-4") -> None:
        self.model_name = model_name
        self.responses = responses
        self._call_index = 0
        self._prompts: list[str] = []

    def generate(self, prompt: str) -> str:
        self._prompts.append(prompt)
        # Match by finding a unique substring of the prompt in our response map
        for key, response in self.responses.items():
            if key in prompt:
                return response
        return ""

    def is_available(self) -> bool:
        return True

    def get_info(self) -> dict:
        return {"model_name": self.model_name}


